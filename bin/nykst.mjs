#!/usr/bin/env node
/**
 * One-command onboarding for AI coding agents.
 *
 *   npx nykst init
 *   npx nykst init --token nyk_... --agent claude,cursor
 *   npx nykst watch
 *
 * The command writes only local agent configuration. It never writes to the
 * repository under analysis and never prints a token.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const DEFAULT_URL = "https://nykst.unifies.codes";
const AGENTS = ["claude", "cursor", "vscode", "windsurf", "codex"];

function parseArgs(argv) {
  const args = { _: [] };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (!value.startsWith("--")) {
      args._.push(value);
      continue;
    }
    const key = value.slice(2);
    const next = argv[index + 1];
    if (next === undefined || next.startsWith("--")) args[key] = true;
    else {
      args[key] = next;
      index += 1;
    }
  }
  return args;
}

function help() {
  return [
    "Nykst agent onboarding",
    "",
    "Usage:",
    "  npx nykst init [options]       write MCP configs for local agents",
    "  npx nykst watch [directory]    patch the graph from local file changes",
    "",
    "Options:",
    "  --token <nyk_...>   Nykst access token (or set NYKST_TOKEN)",
    "  --url <origin>      Nykst origin (default https://nykst.unifies.codes)",
    "  --agent <list>      claude,cursor,vscode,windsurf,codex,all (default all)",
    "  --dir <path>        repository root (default current directory)",
    "  --force             replace an existing nykst entry",
    "  --help              show this help",
  ].join("\n");
}

function readJson(file) {
  if (!existsSync(file)) return {};
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`${file} is not valid JSON: ${error.message}`);
  }
}

function writeJson(file, value) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function mergeServer(file, key, entry, force) {
  const data = readJson(file);
  const servers = data[key] && typeof data[key] === "object" ? data[key] : {};
  if (servers.nykst && !force)
    return { file, changed: false, reason: "existing nykst entry kept (use --force)" };
  writeJson(file, { ...data, [key]: { ...servers, nykst: entry } });
  return { file, changed: true };
}

function endpoint(origin) {
  return `${origin.replace(/\/+$/, "")}/api/mcp`;
}

function httpServer(url, token) {
  return {
    type: "http",
    url,
    headers: { Authorization: `Bearer ${token || "${NYKST_TOKEN}"}` },
  };
}

function selectedAgents(raw) {
  if (!raw || raw === true || raw === "all") return AGENTS;
  const wanted = String(raw)
    .split(",")
    .map((value) => value.trim().toLowerCase())
    .filter(Boolean);
  for (const agent of wanted)
    if (!AGENTS.includes(agent))
      throw new Error(`Unknown agent "${agent}". Choose ${AGENTS.join(", ")} or all.`);
  return wanted;
}

function init(args) {
  const root = resolve(typeof args.dir === "string" ? args.dir : ".");
  mkdirSync(root, { recursive: true });
  const url = typeof args.url === "string" ? args.url : DEFAULT_URL;
  const token = typeof args.token === "string" ? args.token : process.env.NYKST_TOKEN || "";
  const agents = selectedAgents(args.agent);
  const force = Boolean(args.force);
  const mcpUrl = endpoint(url);
  const server = httpServer(mcpUrl, token);
  const results = [];

  const targets = {
    claude: { file: join(root, ".mcp.json"), key: "mcpServers", entry: server },
    cursor: { file: join(root, ".cursor", "mcp.json"), key: "mcpServers", entry: server },
    vscode: { file: join(root, ".vscode", "mcp.json"), key: "servers", entry: server },
    windsurf: { file: join(root, ".windsurf", "mcp.json"), key: "mcpServers", entry: server },
  };
  for (const agent of agents) {
    const target = targets[agent];
    if (target)
      results.push({ agent, ...mergeServer(target.file, target.key, target.entry, force) });
  }

  const canonical = join(root, ".nykst", "mcp.json");
  results.push({
    agent: "canonical",
    ...mergeServer(canonical, "mcpServers", server, force),
  });
  writeJson(join(root, ".nykst", "config.json"), {
    endpoint: mcpUrl,
    agents,
    note: "Generated by npx nykst init. The token is read from NYKST_TOKEN when not supplied.",
  });

  if (agents.includes("codex")) {
    const file = join(root, ".nykst", "codex.toml");
    if (!existsSync(file) || force) {
      writeFileSync(
        file,
        [
          "[mcp_servers.nykst]",
          `url = "${mcpUrl}"`,
          'bearer_token_env_var = "NYKST_TOKEN"',
          "",
        ].join("\n"),
      );
      results.push({ agent: "codex", file, changed: true });
    } else results.push({ agent: "codex", file, changed: false, reason: "existing file kept" });
  }

  const readme = join(root, ".nykst", "README.md");
  writeFileSync(
    readme,
    [
      "# Nykst is connected",
      "",
      `MCP endpoint: \`${mcpUrl}\``,
      "",
      "Generated by `npx nykst init`.",
      "",
      "- Claude Code, Cursor and Windsurf read their config from the files written in this repository.",
      "- VS Code reads `.vscode/mcp.json`; Codex instructions are in `.nykst/codex.toml`.",
      "- Export `NYKST_TOKEN` if a config uses `${NYKST_TOKEN}` instead of a literal token.",
      "- Patch the graph from local edits with `bun scripts/watch.ts` (or `npx nykst watch`).",
      "- Mint or revoke a token at " + `${url.replace(/\/+$/, "")}/mcp`,
      "",
    ].join("\n"),
  );

  console.log(`Nykst onboarding complete for ${agents.join(", ")}.`);
  for (const result of results)
    console.log(
      `  ${result.changed ? "wrote" : "kept "} ${result.file}${result.reason ? ` (${result.reason})` : ""}`,
    );
  console.log(`  wrote ${readme}`);
  if (!token) {
    console.log("");
    console.log(`No token was supplied. Create one at ${url.replace(/\/+$/, "")}/mcp`);
    console.log("then export NYKST_TOKEN before starting the agent.");
  }
  return 0;
}

function watch(args) {
  const root = resolve(typeof args.dir === "string" ? args.dir : ".");
  const script = join(root, "scripts", "watch.ts");
  if (!existsSync(script)) {
    console.error(`Could not find ${script}. Run this command from the Nykst checkout.`);
    return 1;
  }
  const result = spawnSync("bun", [script, ...(args._.slice(1) || [])], {
    cwd: root,
    stdio: "inherit",
  });
  return result.status ?? 1;
}

const args = parseArgs(process.argv.slice(2));
const command = args._[0] ?? "help";
if (args.help || command === "help") {
  console.log(help());
  process.exit(0);
}
try {
  if (command === "init") process.exit(init(args));
  if (command === "watch") process.exit(watch(args));
  console.error(`Unknown command "${command}".\n\n${help()}`);
  process.exit(1);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
